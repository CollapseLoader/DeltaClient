package aethereal.friend;


public class FriendConstructor {
    private String a;

    public FriendConstructor() {
    }

    public FriendConstructor(String name) {
        this.a = name;
    }

    public void a(String name) {
        this.a = name;
    }

    public String a() {
        return this.a;
    }
}
